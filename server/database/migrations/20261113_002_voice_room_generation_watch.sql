-- Гласов чат — постоянно наблюдение на оттеглени имена с неясен CreateRoom
-- (Етап 2в, само добавяща миграция).
--
-- CreateRoom, завършил с timeout (или с повече от един опит), може да бъде
-- изпълнен от LiveKit ПО-КЪСНО — дори след като името е оттеглено и
-- DeleteRoom е потвърден — и да "възкреси" стаята под старото име. Със
-- стар, още валиден токен в нея може да се влезе (потвърдено с реалния
-- LiveKit v1.13.11, тестове 11 и 12). Затова такива имена се наблюдават
-- (ListRooms на 30 s) до watch_until и всяка повторно появила се стая се
-- изтрива. Състоянието е в базата — преживява рестарт на backend-а.
--
--   uncertain_create_at — първият неясен изход на CreateRoom за името
--                         (докато името е живо — само маркер, без sweep);
--   watch_until         — краят на наблюдението; задава се при оттеглянето,
--                         удължава се при ПОТВЪРДЕНОТО изтриване и при всяко
--                         повторно появяване на стаята. NULL = без наблюдение.
--
-- Без нови таблици и без промяна на текущата генерация: колоните се ползват
-- само за редове с неясен CreateRoom.

ALTER TABLE voice_room_generations ADD COLUMN uncertain_create_at TEXT NULL;
ALTER TABLE voice_room_generations ADD COLUMN watch_until TEXT NULL;

-- Кратка заявка "има ли активно наблюдение" и следващ срок — само по
-- редовете с наблюдение (частичен индекс; без пълни сканирания).
CREATE INDEX IF NOT EXISTS idx_voice_room_generations_watch
  ON voice_room_generations(watch_until) WHERE watch_until IS NOT NULL;
