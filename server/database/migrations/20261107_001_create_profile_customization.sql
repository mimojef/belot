-- ─── Регистър на покупките (история на плащанията и сроковете) ────────────
-- Mirror на vip_purchase_ledger: pending ред -> Stripe Checkout -> CAS
-- pending->paid САМО от webhook-а. Цената, дните и артикулът са snapshot в
-- момента на поръчката (по-късна промяна на цената/каталога не я засяга).
--
-- Финансов запис: при изтриване на профил редът остава (profile_id -> NULL,
-- псевдонимният UUID в deleted_profile_id_snapshot — виж
-- profileDeletionExecutor.ts), mirror на 20260902_002.
--
-- Ефект при кредитиране (grant_effect):
--   'new'     — нямаше активна екстра от този вид; нова верига от днес.
--   'extend'  — същият артикул беше активен; дните се добавят към срока.
--   'replace' — различен артикул беше активен; той се заменя веднага,
--               оставащото му време се губи (replaced_* полетата го описват).
-- chain_id групира покупките на една непрекъсната верига от същия артикул —
-- нужно е, за да може refund да преизчисли срока, без да засяга валидните
-- следващи покупки/удължавания (виж applyRefund в store-а).
CREATE TABLE IF NOT EXISTS profile_customization_purchases (
  purchase_id TEXT PRIMARY KEY,
  profile_id TEXT NULL,
  deleted_profile_id_snapshot TEXT NULL,
  kind TEXT NOT NULL CHECK (
    kind IN ('nickname_color', 'message_color', 'emoji_before', 'emoji_after')
  ),
  item_id TEXT NOT NULL,
  item_value_snapshot TEXT NOT NULL CHECK (upper(item_value_snapshot) <> '#F72585'),
  item_label_snapshot TEXT NULL,
  days_snapshot INTEGER NOT NULL CHECK (days_snapshot IN (30, 60, 90, 120, 150, 180)),
  base_price_30_days_cents_snapshot INTEGER NOT NULL CHECK (
    base_price_30_days_cents_snapshot BETWEEN 50 AND 100000
  ),
  -- Точна цена в центове: база × (дни / 30), без отстъпки, без floating point.
  price_cents_snapshot INTEGER NOT NULL,
  currency TEXT NOT NULL DEFAULT 'EUR' CHECK (currency = 'EUR'),
  provider TEXT NOT NULL DEFAULT 'stripe',
  provider_checkout_session_id TEXT UNIQUE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (
    status IN ('pending', 'paid', 'canceled', 'failed', 'refunded')
  ),
  credited_at TEXT NULL,
  grant_effect TEXT NULL CHECK (grant_effect IN ('new', 'extend', 'replace')),
  chain_id TEXT NULL,
  granted_until_snapshot TEXT NULL,
  replaced_item_value_snapshot TEXT NULL,
  replaced_active_until_snapshot TEXT NULL,
  -- Възстановяване на плащане (Stripe refund). refunded_amount_cents е
  -- кумулативната сума от Stripe; пълно възстановяване -> status 'refunded'.
  -- refunded_at без status 'refunded' = частично възстановяване (за преглед)
  -- или refund, пристигнал преди checkout.session.completed.
  refunded_at TEXT NULL,
  refunded_amount_cents INTEGER NULL CHECK (refunded_amount_cents IS NULL OR refunded_amount_cents >= 0),
  refund_stripe_event_id TEXT NULL,
  -- Частично възстановяване: правата остават, но покупката задължително
  -- чака администраторски преглед ('pending' -> 'reviewed' от админ панела).
  refund_review_status TEXT NULL CHECK (refund_review_status IS NULL OR refund_review_status IN ('pending', 'reviewed')),
  -- Причина за прегледа: 'partial_refund' (частично възстановяване — правата
  -- остават) или 'refund_failed' (Stripe refund е неуспешен/отменен, след
  -- като правото вече е анулирано — сумата НЕ е върната; не се възстановява
  -- автоматично, за да не се повреди по-нова покупка/замяна).
  refund_review_reason TEXT NULL CHECK (refund_review_reason IS NULL OR refund_review_reason IN ('partial_refund', 'refund_failed')),
  refund_reviewed_at TEXT NULL,
  -- Кой admin е маркирал прегледа (FK SET NULL при изтриване + име-snapshot,
  -- анонимизиран от profileDeletionExecutor.ts).
  refund_reviewed_by_profile_id TEXT NULL,
  refund_reviewed_by_display_name_snapshot TEXT NULL,
  -- Stripe refund id на последния неуспешен refund (idempotency на
  -- refund.failed / refund.updated / charge.refund.updated).
  refund_failed_refund_id TEXT NULL,
  refund_failed_at TEXT NULL,
  stripe_payment_intent_id TEXT NULL,
  stripe_charge_id TEXT NULL,
  payment_method_type TEXT NULL,
  wallet_type TEXT NULL,
  card_brand TEXT NULL,
  card_last4 TEXT NULL,
  card_country TEXT NULL,
  hidden_at TEXT NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  CHECK (price_cents_snapshot = base_price_30_days_cents_snapshot * (days_snapshot / 30)),
  CHECK (status NOT IN ('paid', 'refunded') OR credited_at IS NOT NULL OR refunded_at IS NOT NULL),
  CHECK (credited_at IS NULL OR (grant_effect IS NOT NULL AND chain_id IS NOT NULL AND granted_until_snapshot IS NOT NULL)),
  FOREIGN KEY (profile_id) REFERENCES profiles(profile_id) ON DELETE SET NULL,
  FOREIGN KEY (refund_reviewed_by_profile_id) REFERENCES profiles(profile_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_profile_customization_purchases_profile
  ON profile_customization_purchases(profile_id, created_at);

CREATE INDEX IF NOT EXISTS idx_profile_customization_purchases_status
  ON profile_customization_purchases(status, credited_at);

CREATE INDEX IF NOT EXISTS idx_profile_customization_purchases_chain
  ON profile_customization_purchases(chain_id)
  WHERE chain_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_profile_customization_purchases_payment_intent
  ON profile_customization_purchases(stripe_payment_intent_id)
  WHERE stripe_payment_intent_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_profile_customization_purchases_refund_review
  ON profile_customization_purchases(refund_review_status)
  WHERE refund_review_status = 'pending';

CREATE INDEX IF NOT EXISTS idx_profile_customization_purchases_deleted_profile_snapshot
  ON profile_customization_purchases(deleted_profile_id_snapshot)
  WHERE deleted_profile_id_snapshot IS NOT NULL;

-- Една видима pending поръчка за същия артикул/срок на профил.
CREATE UNIQUE INDEX IF NOT EXISTS idx_profile_customization_purchases_pending_item
  ON profile_customization_purchases(profile_id, kind, item_id, days_snapshot)
  WHERE status = 'pending' AND hidden_at IS NULL;

-- ─── Режим на достъп (управляван от админ панела, без deploy) ─────────────
-- 'admin_only' — само пълен admin вижда/купува (реални плащания за тест);
-- 'public'     — всички потребители. Текущият режим е последният запис;
-- без записи режимът е 'admin_only' — миграцията/deploy/рестарт НЕ могат да
-- направят функцията публична. Всеки ред е одит: кой admin и кога.
CREATE TABLE IF NOT EXISTS profile_customization_mode_changes (
  change_id TEXT PRIMARY KEY,
  mode TEXT NOT NULL CHECK (mode IN ('admin_only', 'public')),
  previous_mode TEXT NOT NULL CHECK (previous_mode IN ('admin_only', 'public')),
  changed_by_profile_id TEXT NULL,
  changed_by_display_name_snapshot TEXT NULL,
  changed_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  FOREIGN KEY (changed_by_profile_id) REFERENCES profiles(profile_id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_profile_customization_mode_changes_changed_at
  ON profile_customization_mode_changes(changed_at);

-- ─── Текуща активна екстра (по профил и вид) ─────────────────────────────
-- Read-оптимизирано състояние за груповото извличане при показване на
-- съобщения (WHERE profile_id IN (...) AND active_until > now). Изтичането
-- не изисква job — изтекъл ред просто не минава филтъра. Пише се САМО от
-- кредитирането/refund-а в store-а, в същата транзакция като регистъра.
-- Не е финансов запис — изтрива се заедно с профила (CASCADE).
CREATE TABLE IF NOT EXISTS profile_customization_active (
  profile_id TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (
    kind IN ('nickname_color', 'message_color', 'emoji_before', 'emoji_after')
  ),
  item_id TEXT NOT NULL,
  item_value_snapshot TEXT NOT NULL CHECK (upper(item_value_snapshot) <> '#F72585'),
  item_label_snapshot TEXT NULL,
  chain_id TEXT NOT NULL,
  chain_started_at TEXT NOT NULL,
  active_until TEXT NOT NULL,
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  PRIMARY KEY (profile_id, kind),
  CHECK (active_until >= chain_started_at),
  FOREIGN KEY (profile_id) REFERENCES profiles(profile_id) ON DELETE CASCADE
) WITHOUT ROWID;

