-- ─── Каталог с цветове ───────────────────────────────────────────────────
-- hex е неизменим след създаване (тригер по-долу): закупените екстри пазят
-- собствен snapshot, а промяна на цвета под съществуващ артикул би
-- означавала, че купувачите на "същия" артикул виждат различни цветове.
-- #F72585 е запазен за служебните роли (pika_team, marketing) — не може да
-- бъде добавен (CHECK тук + перцептивна проверка за близки нюанси в кода).
CREATE TABLE IF NOT EXISTS profile_customization_colors (
  color_id TEXT PRIMARY KEY CHECK (length(color_id) BETWEEN 1 AND 64),
  hex TEXT NOT NULL UNIQUE CHECK (
    hex GLOB '#[0-9A-F][0-9A-F][0-9A-F][0-9A-F][0-9A-F][0-9A-F]'
    AND hex <> '#F72585'
  ),
  label TEXT NOT NULL CHECK (length(trim(label)) BETWEEN 1 AND 40),
  group_key TEXT NOT NULL CHECK (
    group_key IN ('red', 'orange', 'gold', 'green', 'teal', 'blue', 'purple')
  ),
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

CREATE INDEX IF NOT EXISTS idx_profile_customization_colors_group
  ON profile_customization_colors(group_key, sort_order);

CREATE TRIGGER IF NOT EXISTS trg_profile_customization_colors_hex_immutable
BEFORE UPDATE OF hex ON profile_customization_colors
WHEN NEW.hex IS NOT OLD.hex
BEGIN
  SELECT RAISE(ABORT, 'profile_customization_color_hex_immutable');
END;

