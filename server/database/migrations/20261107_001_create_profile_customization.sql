-- "Персонализация на профила" (Етап 1) — четири независими платени екстри:
--   nickname_color  — цвят на никнейма
--   message_color   — цвят на текста на съобщенията
--   emoji_before    — емоджи пред никнейма
--   emoji_after     — емоджи след никнейма
--
-- Потребителят купува КОНКРЕТЕН цвят/емоджи за 30..180 дни. Същият артикул
-- удължава оставащия срок; различен артикул го заменя веднага след
-- потвърдено плащане (неизползваните дни се губят). Активирането е САМО от
-- Stripe webhook-а (profileCustomizationStore.fulfillPaidPurchase).
--
-- Цялата функционалност е зад PROFILE_CUSTOMIZATION_ENABLED (изключен по
-- подразбиране) и всяка екстра има собствен превключвател за продажба
-- (sales_enabled = 0 по подразбиране) — миграцията сама по себе си не
-- променя нищо видимо за потребителите.
--
-- Всички времена в новите таблици са канонични UTC ISO низове
-- ('YYYY-MM-DDTHH:MM:SS.SSSZ', същият формат като Date.toISOString()), за да
-- са коректни директните текстови сравнения (active_until > now).

-- ─── Настройки на екстрите (цена за 30 дни + продажба вкл./изкл.) ─────────
-- Минимумът 50 цента е минималната сума за Stripe плащане в EUR.
CREATE TABLE IF NOT EXISTS profile_customization_kind_settings (
  kind TEXT PRIMARY KEY CHECK (
    kind IN ('nickname_color', 'message_color', 'emoji_before', 'emoji_after')
  ),
  base_price_30_days_cents INTEGER NOT NULL CHECK (
    base_price_30_days_cents BETWEEN 50 AND 100000
  ),
  sales_enabled INTEGER NOT NULL DEFAULT 0 CHECK (sales_enabled IN (0, 1)),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
);

